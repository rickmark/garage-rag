"""Configuration: one JSON file with a database URL environment override.

The file is **nested** because that is what is pleasant to edit; :class:`Settings`
is **flat** because that is what is pleasant to use from code. :data:`SECTIONS`
is the only thing that knows both shapes, and it drives loading, saving, and
schema generation, so the three can never disagree.

Search order, first match wins:

1. ``--config PATH`` passed explicitly
2. ``./garage.json`` -- a project-local override
3. ``~/.garage.json`` -- the default

JSON cannot carry comments, so every field's documentation lives in the generated
schema, which every config references by URL through its ``$schema`` key. Editors
then validate and describe fields inline, which is what the comments would have
been for -- and because the reference is a URL rather than a path, a config in
``$HOME`` needs no local schema copy beside it.

The schema is generated from this module (``garage config schema --publish``) and
committed under ``docs/.data/``, which the website serves, so :data:`SCHEMA_URL`
resolves. Regenerate it whenever a setting is added, renamed, or documented; a
test fails if a field is left undescribed.

Unknown keys are an **error**, not something ignored. A silently dropped typo in a
config file is a bug you find hours later, wondering why a setting had no effect.
The one exception is :data:`RETIRED_KEYS`: settings that used to exist and were
removed. Those are skipped with a warning so an older file still loads.
"""

