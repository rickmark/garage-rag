class ConfigError(Exception):
    """The configuration file is missing, malformed, or has unknown keys."""


def default_config_path() -> Path:
    """The default location: ``~/.garage.json``."""
    return Path.home() / USER_CONFIG_FILENAME


def repo_schema_path() -> Path:
    """Where the schema is generated for publishing.

    Committed under ``docs/.data``, which the website serves, so :data:`SCHEMA_URL`
    resolves. This is a build artifact, not something written next to a user's
    config.
    """
    return repo_root() / "docs" / SITE_DATA_DIR / SCHEMA_FILENAME


def candidate_paths() -> list[Path]:
    return [Path.cwd() / CONFIG_FILENAME, default_config_path()]


def find_config_file() -> Path | None:
    """First existing config in the search order, or None."""
    return next((p for p in candidate_paths() if p.is_file()), None)


def flatten(document: dict[str, Any]) -> dict[str, Any]:
    """Nested file layout -> flat Settings kwargs.

    Raises :class:`ConfigError` on unknown sections or keys, so a typo is
    reported rather than silently having no effect.
    """
    flat: dict[str, Any] = {}
    for section, body in document.items():
        if section.startswith("$"):
            # $schema and friends are metadata for editors.
            continue
        if section == "sources":
            if not isinstance(body, list):
                raise ConfigError("'sources' must be a list")
            flat["sources"] = body
            continue
        if section not in SECTIONS and section not in RETIRED_KEYS:
            known = ", ".join([*SECTIONS, "sources"])
            raise ConfigError(f"unknown section {section!r}; expected one of: {known}")
        if not isinstance(body, dict):
            raise ConfigError(f"section {section!r} must be an object")
        mapping = SECTIONS.get(section, {})
        for key, value in body.items():
            field = mapping.get(key)
            if field is None and key in RETIRED_KEYS.get(section, frozenset()):
                log.warning("config: %s.%s is no longer a setting and was ignored; remove it", section, key)
                continue
            if field is None:
                raise ConfigError(f"unknown key {key!r} in section {section!r}; expected one of: {', '.join(mapping)}")
            flat[field] = value
    return flat


def nest(
    settings: Settings,
    *,
    include_defaults: bool = True,
    schema_ref: str = SCHEMA_URL,
) -> dict[str, Any]:
    """Flat Settings -> nested file layout."""
    defaults = Settings()
    document: dict[str, Any] = {"$schema": schema_ref}

    for section, mapping in SECTIONS.items():
        body: dict[str, Any] = {}
        for key, field in mapping.items():
            value = getattr(settings, field)
            if not include_defaults and value == getattr(defaults, field):
                continue
            body[key] = value
        if body:
            document[section] = body

    if settings.sources:
        document["sources"] = [
            spec.model_dump(by_alias=True, exclude_defaults=not include_defaults) for spec in settings.sources
        ]
    return document


def load_config(path: Path | None = None) -> Settings:
    """Load configuration from ``path``, or from the search order.

    An explicit ``path`` must exist; with none given, no file at all means the
    defaults.
    """
    resolved = path.expanduser() if path is not None else find_config_file()

    if resolved is None or not resolved.is_file():
        if path is not None:
            searched = ", ".join(str(p) for p in ([resolved] if path else candidate_paths()))
            raise ConfigError(f"no config file found (looked at: {searched}); create one with 'garage config init'")
        # No file at all: defaults are a usable configuration.
        return _apply_database_url_environment(Settings())

    try:
        raw = json.loads(resolved.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ConfigError(f"{resolved} is not valid JSON: {exc}") from exc
    except OSError as exc:
        raise ConfigError(f"cannot read {resolved}: {exc}") from exc

    if not isinstance(raw, dict):
        raise ConfigError(f"{resolved} must contain a JSON object")

    try:
        settings = Settings(**flatten(raw))
    except ValidationError as exc:
        raise ConfigError(f"{resolved}: {exc}") from exc

    settings.config_path = resolved
    return _apply_database_url_environment(settings)


def _apply_database_url_environment(settings: Settings) -> Settings:
    """Apply the app-managed database credential without persisting it in JSON."""
    database_url = os.environ.get("GARAGE_DATABASE_URL")
    if database_url is None:
        return settings
    if not database_url.strip():
        raise ConfigError("GARAGE_DATABASE_URL must not be empty")
    settings.database_url = ensure_psycopg_database_url(database_url)
    return settings


def save_config(settings: Settings, path: Path) -> None:
    """Write ``settings`` to ``path`` atomically.

    ``$schema`` points at the published URL rather than a neighbouring file, so a
    config in ``$HOME`` still validates in an editor with nothing else installed.
    """
    path = path.expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(nest(settings), indent=2, ensure_ascii=False) + "\n"
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(payload, encoding="utf-8")
    temp.replace(path)


def json_schema() -> dict[str, Any]:
    """A JSON Schema for the nested file.

    Hand-assembled from :data:`SECTIONS` plus each field's description, because
    the file shape is nested while the model is flat. This is where the
    documentation lives, since JSON has no comments.
    """
    fields = Settings.model_fields
    properties: dict[str, Any] = {"$schema": {"type": "string", "description": "Path or URL to this schema."}}

    type_map: dict[Any, str] = {
        str: "string",
        int: "integer",
        float: "number",
        bool: "boolean",
    }

    for section, mapping in SECTIONS.items():
        section_props: dict[str, Any] = {}
        for key, name in mapping.items():
            info = fields[name]
            annotation = info.annotation
            entry: dict[str, Any] = {}
            if annotation == list[str]:
                entry["type"] = "array"
                entry["items"] = {"type": "string"}
            elif annotation in type_map:
                entry["type"] = type_map[annotation]
            elif annotation == (str | None):
                entry["type"] = ["string", "null"]
            elif get_origin(annotation) is Literal:
                entry["type"] = "string"
                entry["enum"] = list(get_args(annotation))
            if info.description:
                entry["description"] = info.description
            default = Settings.model_fields[name].get_default(call_default_factory=True)
            if default is not None:
                entry["default"] = default
            section_props[key] = entry
        properties[section] = {
            "type": "object",
            "additionalProperties": False,
            "properties": section_props,
        }

    source_props: dict[str, Any] = {}
    for name, info in SourceSpec.model_fields.items():
        key = info.alias or name
        entry = {}
        if info.annotation is bool:
            entry["type"] = "boolean"
        else:
            entry["type"] = "string"
        if info.description:
            entry["description"] = info.description
        source_props[key] = entry

    properties["sources"] = {
        "type": "array",
        "description": Settings.model_fields["sources"].description,
        "items": {
            "type": "object",
            "additionalProperties": False,
            "required": ["slug", "root"],
            "properties": source_props,
        },
    }

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "garage-rag configuration",
        "type": "object",
        "additionalProperties": False,
        "properties": properties,
    }


def setting_names() -> list[str]:
    """Every ``section.key`` the file accepts, in file order."""
    return [f"{section}.{key}" for section, mapping in SECTIONS.items() for key in mapping]


def resolve_setting(name: str) -> tuple[str, str, str]:
    """``"section.key"`` -> ``(section, key, flat field name)``.

    Raises :class:`ConfigError` naming the valid keys, so a typo on the command
    line is caught before anything is written.
    """
    section, dot, key = name.partition(".")
    if not dot or not section or not key:
        raise ConfigError(f"expected SECTION.KEY, got {name!r}; valid keys: {', '.join(setting_names())}")
    mapping = SECTIONS.get(section)
    if mapping is None:
        raise ConfigError(f"unknown section {section!r}; expected one of: {', '.join(SECTIONS)}")
    field = mapping.get(key)
    if field is None:
        raise ConfigError(f"unknown key {key!r} in section {section!r}; expected one of: {', '.join(mapping)}")
    return section, key, field


_TRUE_WORDS = frozenset({"true", "yes", "on", "1"})
_FALSE_WORDS = frozenset({"false", "no", "off", "0"})


def coerce_setting(field: str, raw: str) -> Any:
    """Turn a command-line string into the value ``Settings.<field>`` expects.

    ``bool`` accepts true/false, yes/no, on/off and 1/0; ``int``/``float`` parse
    numerically; ``list[str]`` splits on commas (an empty string is an empty
    list); an optional string becomes ``None`` for ``""``/``none``/``null``.
    Everything else -- plain strings and the ``Literal`` choices -- is passed
    through for pydantic to validate.
    """
    annotation = Settings.model_fields[field].annotation
    text = raw.strip()
    if annotation is bool:
        lowered = text.lower()
        if lowered in _TRUE_WORDS:
            return True
        if lowered in _FALSE_WORDS:
            return False
        raise ConfigError(f"{field}: expected true/false, yes/no, on/off or 1/0, got {raw!r}")
    if annotation is int:
        try:
            return int(text)
        except ValueError:
            raise ConfigError(f"{field}: expected an integer, got {raw!r}") from None
    if annotation is float:
        try:
            return float(text)
        except ValueError:
            raise ConfigError(f"{field}: expected a number, got {raw!r}") from None
    if annotation == list[str]:
        return [item.strip() for item in text.split(",") if item.strip()]
    if annotation == (str | None) and text.lower() in {"", "none", "null"}:
        return None
    return raw


def read_config_document(path: Path) -> dict[str, Any]:
    """The nested JSON document at ``path``, or ``{}`` when the file does not exist.

    Unlike :func:`load_config` this applies no environment override, so what
    :func:`update_config` writes back is what the file already said plus the
    one change -- never an app-managed database URL from the environment.
    """
    path = path.expanduser()
    if not path.is_file():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ConfigError(f"{path} is not valid JSON: {exc}") from exc
    except OSError as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise ConfigError(f"{path} must contain a JSON object")
    return raw


def update_config(path: Path, name: str, raw_value: str) -> tuple[Settings, Any]:
    """Set ``section.key`` to ``raw_value`` in the file at ``path`` and save it.

    The file is read (defaults when absent), the one value coerced and
    substituted, the whole thing validated by round-tripping through
    :class:`Settings`, and then written with :func:`save_config` -- so the
    nested layout, ``$schema`` and key order come out exactly as ``config init``
    would produce them. Returns the saved settings and the coerced value.
    """
    _section, _key, field = resolve_setting(name)
    value = coerce_setting(field, raw_value)
    flat = flatten(read_config_document(path))
    flat[field] = value
    try:
        settings = Settings(**flat)
    except ValidationError as exc:
        raise ConfigError(f"{name}: {exc}") from exc
    save_config(settings, path)
    settings.config_path = path.expanduser()
    return settings, getattr(settings, field)


_settings: Settings | None = None


def get_settings() -> Settings:
    """Process-wide settings singleton."""
    global _settings
    if _settings is None:
        settings = load_config()
        _settings = settings
        return settings
    else:
        return _settings


def set_settings(settings: Settings) -> None:
    """Install a specific configuration. Used by the CLI's --config option."""
    global _settings
    _settings = settings


def reset_settings() -> None:
    global _settings
    _settings = None


def repo_root() -> Path:
    """Path to the repository root (holds the published ``data/`` artifacts)."""
