class SourceSpec(BaseModel):
    """A source declared in the config file.

    Declared sources are authoritative: every run re-applies them to the
    database. Sources *only* in the database are left alone -- removing a line
    from this file must never silently delete indexed documents.
    """

    model_config = {"extra": "forbid"}

    slug: str = Field(description="Short unique name, e.g. 'dropbox'.")
    root: str = Field(description="Directory or file to index. '~' is expanded.")
    kind: str = Field(
        default="filesystem",
        description="filesystem | git | sqlite | maildir | feed",
    )
    corpus_class: str = Field(
        default="document",
        alias="class",
        description="Default grouping: document | code | communication",
    )
    trust: str = Field(
        default="authored",
        description="Default trust: authored | reference | received",
    )
    include_code: bool = Field(
        default=False,
        description="Index source files as well as documents.",
    )
    allow_cloud_enrichment: bool = Field(
        default=False,
        description=(
            "Permit the cloud OCR fallback for this source. Never honoured for "
            "communication sources."
        ),
    )
    enabled: bool = Field(default=True, description="Set false to skip this source.")

    @property
    def expanded_root(self) -> Path:
        return Path(self.root).expanduser()


class Settings(BaseModel):
    """Flat view of the configuration, as the rest of the code consumes it."""

    model_config = {"extra": "forbid"}

    # ---- database -------------------------------------------------------
    database_url: str = Field(
        default="postgresql+psycopg:///rag",
        description="SQLAlchemy URL for the RAG database (psycopg3 driver).",
    )
    hnsw_ef_search: int = Field(
        default=100,
        description="HNSW probe width at query time. Higher is better recall, slower.",
    )

    # ---- identity -------------------------------------------------------
    self_name: str = Field(
        default="", description="Display name of the corpus owner."
    )
    self_identities: list[str] = Field(
        default_factory=list,
        description=(
            "Identities belonging to the owner as 'kind:value' strings, e.g. "
            "'git_email:me@example.com'. Anything authored by an identity NOT "
            "listed here is treated as reference rather than authored."
        ),
    )

    # ---- embeddings -----------------------------------------------------
    ollama_host: str = Field(
        default="http://localhost:11434",
        description="Base URL of the Ollama server that produces embeddings.",
    )
    default_embedding_model: str = Field(
        default="bge-m3",
        description=(
            "Slug of the model used when a command does not name one. Must be "
            "registered with 'garage register-model' first."
        ),
    )
    embed_batch_size: int = Field(
        default=64, description="Chunks per embedding request."
    )
    embed_max_inflight: int = Field(
        default=1,
        description=(
            "Concurrent embedding requests. Ollama serializes model execution, so "
            "more than one adds contention rather than throughput."
        ),
    )

    # ---- chunking -------------------------------------------------------
    chunk_size: int = Field(
        default=1000, description="Target characters per prose chunk."
    )
    chunk_overlap: int = Field(
        default=150,
        description=(
            "Characters repeated between adjacent prose chunks, so a sentence "
            "spanning a boundary is still retrievable."
        ),
    )
    code_chunk_size: int = Field(
        default=1200,
        description="Target characters per code chunk. Larger, to keep functions intact.",
    )
    code_chunk_overlap: int = Field(
        default=100, description="Characters repeated between adjacent code chunks."
    )
    comms_window_minutes: int = Field(
        default=30,
        description=(
            "Group consecutive messages within this many minutes into one chunk. "
            "Individual messages are too short to embed usefully."
        ),
    )
    comms_window_messages: int = Field(
        default=20,
        description="Also close a conversation window after this many messages.",
    )

    # ---- cloud placeholders ---------------------------------------------
    materialize_placeholders: bool = Field(
        default=False,
        description=(
            "Download cloud placeholder files when encountered. Reading a stub "
            "asks the provider to fetch it, so a large online-only folder can "
            "mean hundreds of gigabytes. Bounded by the limits below."
        ),
    )
    materialize_limit: int = Field(
        default=2000, description="Files materialized per run; 0 means unlimited."
    )
    materialize_max_bytes: int = Field(
        default=20 * 1024**3, description="Byte budget per run; 0 means unlimited."
    )
    materialize_timeout_seconds: float = Field(
        default=120.0,
        description=(
            "Give up on a single download that never arrives. A stalled provider "
            "cannot be cancelled, so this stops it blocking the run."
        ),
    )

    # ---- MCP server -----------------------------------------------------
    mcp_host: str = Field(
        default="127.0.0.1",
        description=(
            "Bind address. This server has no authentication and exposes the "
            "whole corpus, so a non-loopback address needs --allow-remote."
        ),
    )
    mcp_port: int = Field(default=8787, description="Port for the HTTP transport.")
    mcp_http_path: str = Field(
        default="/mcp", description="HTTP route the MCP endpoint is served on."
    )

    # ---- quality guards -------------------------------------------------
    max_chunks_per_document: int = Field(
        default=1500,
        description="Backstop so no single document can dominate the index.",
    )
    reject_machine_generated: bool = Field(
        default=True,
        description="Reject logs, dumps, and checksum manifests by content shape.",
    )

    # ---- extraction -----------------------------------------------------
    max_file_bytes: int = Field(
        default=64 * 1024 * 1024,
        description="Skip files larger than this; usually archives or disk images.",
    )
    pdf_min_chars_per_page: int = Field(
        default=32,
        description="Below this, escalate a PDF page from pypdf to pdfplumber.",
    )
    ocr_min_confidence: float = Field(
        default=60.0,
        description="Mean Tesseract word confidence below which cloud OCR is considered.",
    )
    ocr_min_chars: int = Field(
        default=16,
        description=(
            "Below this many characters an image is treated as having no text. "
            "Most images in a source tree are icons."
        ),
    )
    extract_workers: int = Field(
        default=10,
        description="Extraction worker processes. Leave headroom for Postgres and Ollama.",
    )

    # ---- cloud ----------------------------------------------------------
    enable_cloud_ocr: bool = Field(
        default=False,
        description="Allow the Claude vision fallback for unreadable images.",
    )
    cloud_ocr_model: str = Field(
        default="claude-opus-4-8",
        description="Model used for the vision OCR fallback.",
    )
    cloud_ocr_max_images: int = Field(
        default=500, description="Cap on images escalated to the cloud per run."
    )
    api_key_file: str | None = Field(
        default=None,
        description=(
            "Path to a file containing the Anthropic API key. Kept out of this "
            "file so the config itself holds no secrets."
        ),
    )

    # ---- sources --------------------------------------------------------
    sources: list[SourceSpec] = Field(
        default_factory=list,
        description=(
            "Sources to index. Declared sources are re-applied on every run; "
            "sources present only in the database are left untouched."
        ),
    )

    # Where this configuration came from. Not part of the file.
    config_path: Path | None = Field(default=None, exclude=True)

    # ---- derived --------------------------------------------------------
    def self_identity_pairs(self) -> list[tuple[str, str]]:
        """Parse ``self_identities`` into ``(kind, value)`` tuples."""
        pairs: list[tuple[str, str]] = []
        for raw in self.self_identities:
            kind, _, value = raw.partition(":")
            if value:
                pairs.append((kind.strip(), value.strip()))
        return pairs

    def read_api_key(self) -> str | None:
        """Load the Anthropic key from ``api_key_file``, if configured.

        Returns None rather than raising when unset, so the cloud path degrades
        to local-only instead of failing the whole run.
        """
        if not self.api_key_file:
            return None
        path = Path(self.api_key_file).expanduser()
        try:
            key = path.read_text(encoding="utf-8").strip()
        except OSError:
            return None
        return key or None

    def source(self, slug: str) -> SourceSpec | None:
        return next((s for s in self.sources if s.slug == slug), None)


