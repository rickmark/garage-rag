class ConfigError(Exception):
    """The configuration file is missing, malformed, or has unknown keys."""


def default_config_path() -> Path:
    """The default location: ``~/.garage.json``."""
    return Path.home() / USER_CONFIG_FILENAME


def repo_schema_path() -> Path:
    """Where the schema is generated for publishing.

    Committed at the repository root so that :data:`SCHEMA_URL` resolves. This is
    a build artifact, not something written next to a user's config.
    """
    return repo_root() / SCHEMA_FILENAME


def candidate_paths() -> list[Path]:
    return [Path.cwd() / CONFIG_FILENAME, default_config_path()]


def find_config_file() -> Path | None:
    """First existing config in the search order, or None."""
    return next((p for p in candidate_paths() if p.is_file()), None)


def flatten(document: dict[str, Any]) -> dict[str, Any]:
    """Nested file layout -> flat Settings kwargs.

    Raises :class:`ConfigError` on unknown sections or keys, so a typo is
    reported rather than silently having no effect.
    """
    flat: dict[str, Any] = {}
    for section, body in document.items():
        if section.startswith("$"):
            # $schema and friends are metadata for editors.
            continue
        if section == "sources":
            if not isinstance(body, list):
                raise ConfigError("'sources' must be a list")
            flat["sources"] = body
            continue
        if section not in SECTIONS:
            known = ", ".join([*SECTIONS, "sources"])
            raise ConfigError(f"unknown section {section!r}; expected one of: {known}")
        if not isinstance(body, dict):
            raise ConfigError(f"section {section!r} must be an object")
        mapping = SECTIONS[section]
        for key, value in body.items():
            field = mapping.get(key)
            if field is None:
                raise ConfigError(
                    f"unknown key {key!r} in section {section!r}; "
                    f"expected one of: {', '.join(mapping)}"
                )
            flat[field] = value
    return flat


def nest(
    settings: Settings,
    *,
    include_defaults: bool = True,
    schema_ref: str = SCHEMA_URL,
) -> dict[str, Any]:
    """Flat Settings -> nested file layout."""
    defaults = Settings()
    document: dict[str, Any] = {"$schema": schema_ref}

    for section, mapping in SECTIONS.items():
        body: dict[str, Any] = {}
        for key, field in mapping.items():
            value = getattr(settings, field)
            if not include_defaults and value == getattr(defaults, field):
                continue
            body[key] = value
        if body:
            document[section] = body

    if settings.sources:
        document["sources"] = [
            spec.model_dump(by_alias=True, exclude_defaults=not include_defaults)
            for spec in settings.sources
        ]
    return document


def load_config(path: Path | None = None, *, required: bool = False) -> Settings:
    """Load configuration from ``path``, or from the search order."""
    resolved = path.expanduser() if path is not None else find_config_file()

    if resolved is None or not resolved.is_file():
        if required or path is not None:
            searched = ", ".join(str(p) for p in ([resolved] if path else candidate_paths()))
            raise ConfigError(
                f"no config file found (looked at: {searched}); "
                "create one with 'garage config init'"
            )
        # No file at all: defaults are a usable configuration.
        return Settings()

    try:
        raw = json.loads(resolved.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ConfigError(f"{resolved} is not valid JSON: {exc}") from exc
    except OSError as exc:
        raise ConfigError(f"cannot read {resolved}: {exc}") from exc

    if not isinstance(raw, dict):
        raise ConfigError(f"{resolved} must contain a JSON object")

    try:
        settings = Settings(**flatten(raw))
    except ValidationError as exc:
        raise ConfigError(f"{resolved}: {exc}") from exc

    settings.config_path = resolved
    return settings


def save_config(settings: Settings, path: Path) -> None:
    """Write ``settings`` to ``path`` atomically.

    ``$schema`` points at the published URL rather than a neighbouring file, so a
    config in ``$HOME`` still validates in an editor with nothing else installed.
    """
    path = path.expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(nest(settings), indent=2, ensure_ascii=False) + "\n"
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(payload, encoding="utf-8")
    temp.replace(path)


def json_schema() -> dict[str, Any]:
    """A JSON Schema for the nested file.

    Hand-assembled from :data:`SECTIONS` plus each field's description, because
    the file shape is nested while the model is flat. This is where the
    documentation lives, since JSON has no comments.
    """
    fields = Settings.model_fields
    properties: dict[str, Any] = {
        "$schema": {"type": "string", "description": "Path or URL to this schema."}
    }

    type_map: dict[Any, str] = {
        str: "string",
        int: "integer",
        float: "number",
        bool: "boolean",
    }

    for section, mapping in SECTIONS.items():
        section_props: dict[str, Any] = {}
        for key, name in mapping.items():
            info = fields[name]
            annotation = info.annotation
            entry: dict[str, Any] = {}
            if annotation == list[str]:
                entry["type"] = "array"
                entry["items"] = {"type": "string"}
            elif annotation in type_map:
                entry["type"] = type_map[annotation]
            elif annotation == (str | None):
                entry["type"] = ["string", "null"]
            if info.description:
                entry["description"] = info.description
            default = Settings.model_fields[name].get_default(call_default_factory=True)
            if default is not None:
                entry["default"] = default
            section_props[key] = entry
        properties[section] = {
            "type": "object",
            "additionalProperties": False,
            "properties": section_props,
        }

    source_props: dict[str, Any] = {}
    for name, info in SourceSpec.model_fields.items():
        key = info.alias or name
        entry = {}
        if info.annotation is bool:
            entry["type"] = "boolean"
        else:
            entry["type"] = "string"
        if info.description:
            entry["description"] = info.description
        source_props[key] = entry

    properties["sources"] = {
        "type": "array",
        "description": Settings.model_fields["sources"].description,
        "items": {
            "type": "object",
            "additionalProperties": False,
            "required": ["slug", "root"],
            "properties": source_props,
        },
    }

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "garage-rag configuration",
        "type": "object",
        "additionalProperties": False,
        "properties": properties,
    }


_settings: Settings | None = None


def get_settings() -> Settings:
    """Process-wide settings singleton."""
    global _settings
    if _settings is None:
        _settings = load_config()
    return _settings


def set_settings(settings: Settings) -> None:
    """Install a specific configuration. Used by the CLI's --config option."""
    global _settings
    _settings = settings


def reset_settings() -> None:
    global _settings
    _settings = None


def repo_root() -> Path:
    """Path to the installed package's project root (holds ``sql/``)."""
    return Path(__file__).resolve().parent.parent.parent


# Kept so modules importing this name keep working; the MCP server no longer
# depends on an environment variable to find its configuration.
def python_executable() -> str:
    return sys.executable
