"""Configuration, loaded from environment / .env.

Every tunable lives here so that ingest, search, and the MCP server agree on
the same values without passing them around.
"""

from __future__ import annotations

from pathlib import Path

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict

# Directory names that are never worth indexing. Skipping these at the walker
# level is what keeps ~/Developer at ~18k documents instead of ~36k.
